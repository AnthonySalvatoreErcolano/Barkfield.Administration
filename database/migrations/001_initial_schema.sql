/*
    Barkfield Road — Auto-Ship & Logistics
    Migration 001: initial schema
    Target: Azure SQL Database (SQL Server)

    Conventions
      - Surrogate keys are UNIQUEIDENTIFIER, generated by the application, never by the
        database. The domain's Create() factories assign ids, so NEWID() defaults would
        silently diverge from what the code inserted.
      - Enums are stored as TINYINT with CHECK constraints naming the valid values.
        Update the constraint whenever the matching C# enum gains a member.
      - Money is DECIMAL(10,2). Coordinates are DECIMAL(9,6).
      - Timestamps are DATETIME2(3) and always UTC. Pure calendar dates use DATE, and
        time-of-day windows use TIME(0).
      - Value objects are flattened: Address becomes Street, City, State, ZipCode;
        TimeWindow becomes a Start and an End column; GeoPoint becomes a Latitude
        and a Longitude column.
      - Cascades are used only inside an aggregate. Anything crossing an aggregate
        boundary is NO ACTION, both to preserve history and to avoid SQL Server's
        multiple-cascade-path restriction.
*/

