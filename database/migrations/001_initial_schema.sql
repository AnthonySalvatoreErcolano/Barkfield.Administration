/*  Flattens user -> role -> permission for the authorization filter, which checks a
    permission name against a user id on every guarded request (cached 5 minutes). */
CREATE VIEW dbo.UserPermissions
AS
    SELECT DISTINCT
        ur.UserId,
        p.Name AS PermissionName
    FROM dbo.UserRoles           ur
    INNER JOIN dbo.RolePermissions rp ON rp.RoleId = ur.RoleId
    INNER JOIN dbo.Permissions     p  ON p.Id = rp.PermissionId;
GO

