/*  Where a customer receives deliveries. Every column maps onto a field sent to the
    routing provider: address, instructions, duration and the time window. */
CREATE TABLE dbo.DeliveryLocations
(
    Id                      UNIQUEIDENTIFIER    NOT NULL CONSTRAINT PK_DeliveryLocations PRIMARY KEY,
    CustomerId              UNIQUEIDENTIFIER    NOT NULL,
    Label                   NVARCHAR(100)       NOT NULL,

    Street                  NVARCHAR(200)       NOT NULL,
    City                    NVARCHAR(100)       NOT NULL,
    State                   NVARCHAR(50)        NOT NULL,
    ZipCode                 NVARCHAR(20)        NOT NULL,

    -- Optional. Routific geocodes from the address; these are stored only when a
    -- provider hands them back, and become required if routing comes in-house.
    Latitude                DECIMAL(9,6)        NULL,
    Longitude               DECIMAL(9,6)        NULL,

    -- Driver-facing: gate codes, "leave at side door", "dog in yard".
    AccessNotes             NVARCHAR(1000)      NULL,

    ServiceDurationMinutes  INT                 NOT NULL CONSTRAINT DF_DeliveryLocations_Duration DEFAULT (5),
    PreferredWindowStart    TIME(0)             NULL,
    PreferredWindowEnd      TIME(0)             NULL,

    IsDefault               BIT                 NOT NULL CONSTRAINT DF_DeliveryLocations_IsDefault DEFAULT (0),
    IsActive                BIT                 NOT NULL CONSTRAINT DF_DeliveryLocations_IsActive DEFAULT (1),
    CreatedAt               DATETIME2(3)        NOT NULL,
    UpdatedAt               DATETIME2(3)        NULL,

    CONSTRAINT FK_DeliveryLocations_Customers
        FOREIGN KEY (CustomerId) REFERENCES dbo.Customers (Id) ON DELETE CASCADE,
    CONSTRAINT CK_DeliveryLocations_Duration
        CHECK (ServiceDurationMinutes BETWEEN 0 AND 480),
    CONSTRAINT CK_DeliveryLocations_Window
        CHECK (PreferredWindowStart IS NULL OR PreferredWindowEnd IS NULL
               OR PreferredWindowEnd > PreferredWindowStart),
    CONSTRAINT CK_DeliveryLocations_Coordinates
        CHECK ((Latitude IS NULL AND Longitude IS NULL)
               OR (Latitude IS NOT NULL AND Longitude IS NOT NULL))
);
GO

