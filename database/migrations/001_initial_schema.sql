/*  Carries no delivery outcome. Delivered or failed lives on Deliveries, so the two
    can never disagree. LoadedAt is ours and survives a republish. */
CREATE TABLE dbo.RouteStops
(
    Id                      UNIQUEIDENTIFIER    NOT NULL CONSTRAINT PK_RouteStops PRIMARY KEY,
    RouteId                 UNIQUEIDENTIFIER    NOT NULL,
    DeliveryId              UNIQUEIDENTIFIER    NOT NULL,

    SequenceOrder           INT                 NOT NULL,
    ExternalStopId          NVARCHAR(128)       NULL,

    PlannedArrival          TIME(0)             NULL,
    PlannedDeparture        TIME(0)             NULL,
    ActualArrival           TIME(0)             NULL,
    ActualDeparture         TIME(0)             NULL,
    DistanceFromPreviousKm  DECIMAL(9,3)        NULL,

    LoadedAt                DATETIME2(3)        NULL,
    CreatedAt               DATETIME2(3)        NOT NULL,
    UpdatedAt               DATETIME2(3)        NULL,

    CONSTRAINT FK_RouteStops_Routes
        FOREIGN KEY (RouteId) REFERENCES dbo.Routes (Id) ON DELETE CASCADE,
    CONSTRAINT FK_RouteStops_Deliveries
        FOREIGN KEY (DeliveryId) REFERENCES dbo.Deliveries (Id)
);
GO

CREATE UNIQUE INDEX UX_RouteStops_Delivery ON dbo.RouteStops (RouteId, DeliveryId);
CREATE INDEX IX_RouteStops_RouteId ON dbo.RouteStops (RouteId, SequenceOrder);
CREATE INDEX IX_RouteStops_DeliveryId ON dbo.RouteStops (DeliveryId);
GO

/* ============================================================================
   WEBHOOK IDEMPOTENCY

   The routing provider retries any webhook it does not get a 200 for, and events can
   arrive out of order. Every handler records the provider's event id here first and
   skips anything already present.
   ============================================================================ */

CREATE TABLE dbo.WebhookEvents
(
    EventId         NVARCHAR(200)   NOT NULL CONSTRAINT PK_WebhookEvents PRIMARY KEY,
    Provider        NVARCHAR(50)    NOT NULL,
    Topic           NVARCHAR(100)   NOT NULL,
    ReceivedAt      DATETIME2(3)    NOT NULL,
    ProcessedAt     DATETIME2(3)    NULL,
    Payload         NVARCHAR(MAX)   NULL,
    ProcessingError NVARCHAR(MAX)   NULL
);
GO

CREATE INDEX IX_WebhookEvents_ReceivedAt ON dbo.WebhookEvents (ReceivedAt DESC);
CREATE INDEX IX_WebhookEvents_Unprocessed
    ON dbo.WebhookEvents (Topic, ReceivedAt) WHERE ProcessedAt IS NULL;
GO
